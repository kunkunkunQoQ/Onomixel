package dev.kunkun.onomixel.sound;

import java.util.Objects;

/**
 * Acoustic Environment Reactor (多环境物理声学反应堆).
 * <p>
 * Translates physical medium properties and cavity acoustics into visual morphing and delays:
 * 1. Underwater Acoustic Damping & Refraction:
 *    - Switches speed of sound from 343 m/s to 1500 m/s when both emitter and listener are submerged.
 *    - Applies refractive sinusoidal wobble: deltaY = A * sin(omega * t + k * x).
 *    - 25% LERP hydrological tinting towards biome water color with micro-bubble particles.
 *    - 1.25x lifetime stretching with Cubic Ease-Out damping.
 * 2. Cave Reverberation & Ghost Echo Tail:
 *    - Underground enclosed cavities (Y &lt; 0 or enclosed cavity) trigger Ghost Echo Layer.
 *    - Echo generated after 0.18s~0.32s delay along normal rebound direction.
 *    - Morphological degradation: scale 0.75x, alpha &lt;= 40%, weakened brackets ("轰！！" -&gt; "（轰……）").
 * 3. Thin-Air Dissolve & Void Silence:
 *    - High altitude (Y &gt; 200) or End Void contracts visual scale by 30% (0.70x) and triggers
 *      particulate dissolve instead of block fade.
 * <p>
 * Zero Minecraft runtime dependencies for pure JVM testability and high-performance execution.
 */
public final class AcousticEnvironmentReactor {

    // 1. Medium Speed of Sound
    public static final double AIR_SPEED_OF_SOUND = 343.0; // m/s
    public static final double WATER_SPEED_OF_SOUND = 1500.0; // m/s

    // 2. Underwater Refractive Wobble and Damping Constants
    public static final double WOBBLE_AMPLITUDE = 0.04; // meters (A_fluid)
    public static final double WOBBLE_FREQUENCY = 3.2; // rad/s (omega)
    public static final double WOBBLE_WAVENUMBER = 2.0; // rad/m (k)
    public static final float WATER_TINT_FACTOR = 0.25f; // 25% LERP
    public static final double WATER_LIFETIME_MULTIPLIER = 1.25; // 1.25x duration

    // 3. Cave Echo Constants
    public static final double MIN_ECHO_DELAY = 0.18; // seconds
    public static final double MAX_ECHO_DELAY = 0.32; // seconds
    public static final double DEFAULT_ECHO_DELAY = 0.25; // seconds
    public static final float ECHO_SCALE = 0.75f; // 0.75x scale
    public static final float ECHO_MAX_ALPHA = 0.40f; // 40% alpha
    public static final double DEFAULT_REBOUND_DISTANCE = 0.50; // meters

    // 4. Thin Air / Void Constants
    public static final double THIN_AIR_MIN_Y = 200.0;
    public static final float THIN_AIR_SCALE = 0.70f; // 30% shrinkage (0.70x)
    public static final double THIN_AIR_DISTANCE_SHRINK = 0.70;

    private AcousticEnvironmentReactor() {}

    /**
     * Physical acoustic environment classification.
     */
    public enum EnvironmentType {
        UNDERWATER,
        CAVE,
        THIN_AIR,
        NORMAL
    }

    /**
     * Secondary companion ghost echo entity generated by cave cavity reverberation.
     */
    public record GhostEcho(
            String text,
            double delaySeconds,
            float alpha,
            float scale,
            double x,
            double y,
            double z,
            double normalX,
            double normalY,
            double normalZ
    ) {
        public GhostEcho {
            Objects.requireNonNull(text, "GhostEcho text cannot be null");
            delaySeconds = Double.isFinite(delaySeconds) ? Math.clamp(delaySeconds, MIN_ECHO_DELAY, MAX_ECHO_DELAY) : DEFAULT_ECHO_DELAY;
            alpha = Float.isFinite(alpha) ? Math.clamp(alpha, 0.0f, ECHO_MAX_ALPHA) : ECHO_MAX_ALPHA;
            scale = Float.isFinite(scale) && scale > 0.0f ? scale : ECHO_SCALE;
            if (!Double.isFinite(x) || !Double.isFinite(y) || !Double.isFinite(z)) {
                throw new IllegalArgumentException("GhostEcho coordinates must be finite: (" + x + ", " + y + ", " + z + ")");
            }
            if (!Double.isFinite(normalX) || !Double.isFinite(normalY) || !Double.isFinite(normalZ)) {
                throw new IllegalArgumentException("GhostEcho normal vector must be finite: (" + normalX + ", " + normalY + ", " + normalZ + ")");
            }
        }
    }

    /**
     * Synthesized acoustic reaction result applied to caption rendering and lifecycle.
     */
    public record AcousticReaction(
            EnvironmentType environment,
            double speedOfSound,
            double delaySeconds,
            double durationMultiplier,
            float scaleMultiplier,
            float alphaMultiplier,
            int tintedColor,
            boolean hasBubbleParticles,
            boolean isParticulateDissolve,
            GhostEcho ghostEcho
    ) {
        public AcousticReaction {
            Objects.requireNonNull(environment, "environment cannot be null");
            if (!Double.isFinite(speedOfSound) || speedOfSound <= 0.0) {
                throw new IllegalArgumentException("speedOfSound must be positive and finite: " + speedOfSound);
            }
            if (!Double.isFinite(delaySeconds) || delaySeconds < 0.0) {
                throw new IllegalArgumentException("delaySeconds must be non-negative and finite: " + delaySeconds);
            }
            if (!Double.isFinite(durationMultiplier) || durationMultiplier <= 0.0) {
                throw new IllegalArgumentException("durationMultiplier must be positive and finite: " + durationMultiplier);
            }
            if (!Float.isFinite(scaleMultiplier) || scaleMultiplier <= 0.0f) {
                throw new IllegalArgumentException("scaleMultiplier must be positive and finite: " + scaleMultiplier);
            }
            if (!Float.isFinite(alphaMultiplier) || alphaMultiplier < 0.0f) {
                throw new IllegalArgumentException("alphaMultiplier must be non-negative and finite: " + alphaMultiplier);
            }
        }

        public boolean hasGhostEcho() {
            return ghostEcho != null;
        }
    }

    /**
     * Determines the physical acoustic environment.
     */
    public static EnvironmentType determineEnvironment(
            boolean sourceUnderwater,
            boolean cameraUnderwater,
            double y,
            boolean enclosedCavity,
            boolean isVoidOrEnd
    ) {
        if (sourceUnderwater && cameraUnderwater) {
            return EnvironmentType.UNDERWATER;
        }
        if (isCaveEnvironment(y, enclosedCavity)) {
            return EnvironmentType.CAVE;
        }
        if (isThinAir(y, isVoidOrEnd)) {
            return EnvironmentType.THIN_AIR;
        }
        return EnvironmentType.NORMAL;
    }

    /**
     * Returns the acoustic propagation speed depending on immersion state.
     */
    public static double calculateSpeedOfSound(boolean sourceUnderwater, boolean cameraUnderwater) {
        return (sourceUnderwater && cameraUnderwater) ? WATER_SPEED_OF_SOUND : AIR_SPEED_OF_SOUND;
    }

    /**
     * Calculates the physical sound propagation delay in nanoseconds.
     */
    public static long calculateAcousticDelayNanos(double distance, boolean isUnderwater) {
        if (!Double.isFinite(distance) || distance <= 0.0) {
            return 0L;
        }
        double speed = isUnderwater ? WATER_SPEED_OF_SOUND : AIR_SPEED_OF_SOUND;
        double delaySeconds = distance / speed;
        return Math.round(delaySeconds * 1_000_000_000L);
    }

    /**
     * Calculates the refractive sinusoidal micro-wobble offset for underwater text.
     * <p>
     * Equation: deltaY = A_fluid * sin(omega * t + k * x)
     */
    public static double calculateRefractiveWobble(double tSeconds, double charX) {
        if (!Double.isFinite(tSeconds) || !Double.isFinite(charX)) {
            return 0.0;
        }
        return WOBBLE_AMPLITUDE * Math.sin(WOBBLE_FREQUENCY * tSeconds + WOBBLE_WAVENUMBER * charX);
    }

    /**
     * Interpolates RGB color towards a target water color by a given factor.
     */
    public static int lerpColor(int baseRgb, int targetRgb, float factor) {
        float f = Math.clamp(factor, 0.0f, 1.0f);
        int r1 = (baseRgb >> 16) & 0xFF;
        int g1 = (baseRgb >> 8) & 0xFF;
        int b1 = baseRgb & 0xFF;

        int r2 = (targetRgb >> 16) & 0xFF;
        int g2 = (targetRgb >> 8) & 0xFF;
        int b2 = targetRgb & 0xFF;

        int r = Math.clamp(Math.round(r1 + (r2 - r1) * f), 0, 255);
        int g = Math.clamp(Math.round(g1 + (g2 - g1) * f), 0, 255);
        int b = Math.clamp(Math.round(b1 + (b2 - b1) * f), 0, 255);

        return (r << 16) | (g << 8) | b;
    }

    /**
     * Performs 25% LERP hydrological tinting towards the biome's water color.
     */
    public static int tintHydrological(int baseRgb, int waterColorRgb) {
        return lerpColor(baseRgb, waterColorRgb, WATER_TINT_FACTOR);
    }

    /**
     * Calculates stretched lifetime for underwater sounds (1.25x).
     */
    public static double calculateUnderwaterDuration(double baseDurationSeconds) {
        if (!Double.isFinite(baseDurationSeconds) || baseDurationSeconds <= 0.0) {
            return 0.0;
        }
        return baseDurationSeconds * WATER_LIFETIME_MULTIPLIER;
    }

    /**
     * Standard Cubic Ease-Out curve: f(t) = 1 - (1 - t)^3.
     */
    public static double cubicEaseOut(double t) {
        if (!Double.isFinite(t) || t <= 0.0) return 0.0;
        if (t >= 1.0) return 1.0;
        double inv = 1.0 - t;
        return 1.0 - (inv * inv * inv);
    }

    /**
     * Evaluates damped alpha during the fade-out phase using Cubic Ease-Out.
     */
    public static float evaluateDampedAlpha(double elapsedSeconds, double totalDurationSeconds, double fadeOutSeconds) {
        if (!Double.isFinite(elapsedSeconds) || !Double.isFinite(totalDurationSeconds)
                || totalDurationSeconds <= 0.0 || elapsedSeconds >= totalDurationSeconds) {
            return 0.0f;
        }
        if (elapsedSeconds <= 0.0) {
            return 1.0f;
        }

        double fadeDuration = (Double.isFinite(fadeOutSeconds) && fadeOutSeconds > 0.0)
                ? Math.min(fadeOutSeconds, totalDurationSeconds)
                : Math.min(0.35, totalDurationSeconds * 0.3);

        double fadeStart = totalDurationSeconds - fadeDuration;
        if (elapsedSeconds < fadeStart) {
            return 1.0f;
        }

        double fadeProgress = Math.clamp((elapsedSeconds - fadeStart) / fadeDuration, 0.0, 1.0);
        double remainingAlpha = 1.0 - cubicEaseOut(fadeProgress);
        return (float) Math.clamp(remainingAlpha, 0.0, 1.0);
    }

    /**
     * Checks if the position corresponds to a deep cave or enclosed cavity.
     */
    public static boolean isCaveEnvironment(double y, boolean enclosedCavity) {
        return (Double.isFinite(y) && y < 0.0) || enclosedCavity;
    }

    /**
     * Transforms primary onomatopoeia text into weakened echo representation.
     * <p>
     * Example: "轰！！" -&gt; "（轰……）"
     */
    public static String weakenEchoText(String primaryText) {
        if (primaryText == null || primaryText.isEmpty()) {
            return "（……）";
        }

        // Strip loud punctuation at the end: ! ！ ? ？ . 。 ~
        int len = primaryText.length();
        int end = len;
        while (end > 0) {
            char c = primaryText.charAt(end - 1);
            if (c == '!' || c == '！' || c == '?' || c == '？' || c == '.' || c == '。' || c == '~') {
                end--;
            } else {
                break;
            }
        }

        String core = (end > 0) ? primaryText.substring(0, end) : "";
        if (core.isEmpty()) {
            return "（……）";
        }
        return "（" + core + "……）";
    }

    /**
     * Generates a secondary companion Ghost Echo entity.
     */
    public static GhostEcho createGhostEcho(
            String primaryText,
            double originX,
            double originY,
            double originZ,
            double normalX,
            double normalY,
            double normalZ
    ) {
        return createGhostEcho(primaryText, originX, originY, originZ, normalX, normalY, normalZ, DEFAULT_ECHO_DELAY);
    }

    /**
     * Generates a secondary companion Ghost Echo entity with explicit delay.
     */
    public static GhostEcho createGhostEcho(
            String primaryText,
            double originX,
            double originY,
            double originZ,
            double normalX,
            double normalY,
            double normalZ,
            double delaySeconds
    ) {
        if (!Double.isFinite(originX) || !Double.isFinite(originY) || !Double.isFinite(originZ)) {
            throw new IllegalArgumentException("Origin coordinates must be finite: (" + originX + ", " + originY + ", " + originZ + ")");
        }

        double delay = Math.clamp(
                Double.isFinite(delaySeconds) ? delaySeconds : DEFAULT_ECHO_DELAY,
                MIN_ECHO_DELAY,
                MAX_ECHO_DELAY
        );

        double nx = Double.isFinite(normalX) ? normalX : 0.0;
        double ny = Double.isFinite(normalY) ? normalY : 1.0;
        double nz = Double.isFinite(normalZ) ? normalZ : 0.0;
        double lenSq = nx * nx + ny * ny + nz * nz;
        if (lenSq < 1e-6) {
            nx = 0.0;
            ny = 1.0;
            nz = 0.0;
        } else {
            double len = Math.sqrt(lenSq);
            nx /= len;
            ny /= len;
            nz /= len;
        }

        double echoX = originX + nx * DEFAULT_REBOUND_DISTANCE;
        double echoY = originY + ny * DEFAULT_REBOUND_DISTANCE;
        double echoZ = originZ + nz * DEFAULT_REBOUND_DISTANCE;

        String echoText = weakenEchoText(primaryText);
        return new GhostEcho(echoText, delay, ECHO_MAX_ALPHA, ECHO_SCALE, echoX, echoY, echoZ, nx, ny, nz);
    }

    /**
     * Checks if coordinates fall into thin-air high altitude or void.
     */
    public static boolean isThinAir(double y, boolean isVoidOrEnd) {
        return (Double.isFinite(y) && y > THIN_AIR_MIN_Y) || isVoidOrEnd;
    }

    /**
     * Synthesizes full physical acoustic reaction for a sound event.
     */
    public static AcousticReaction react(
            String text,
            int baseRgb,
            double distance,
            double x,
            double y,
            double z,
            double normalX,
            double normalY,
            double normalZ,
            boolean sourceUnderwater,
            boolean cameraUnderwater,
            int biomeWaterColorRgb,
            boolean enclosedCavity,
            boolean isVoidOrEnd
    ) {
        String safeText = (text != null) ? text : "";
        double safeX = Double.isFinite(x) ? x : 0.0;
        double safeY = Double.isFinite(y) ? y : 0.0;
        double safeZ = Double.isFinite(z) ? z : 0.0;
        double safeDist = (Double.isFinite(distance) && distance > 0.0) ? distance : 0.0;

        EnvironmentType env = determineEnvironment(sourceUnderwater, cameraUnderwater, safeY, enclosedCavity, isVoidOrEnd);
        double speed = (env == EnvironmentType.UNDERWATER) ? WATER_SPEED_OF_SOUND : AIR_SPEED_OF_SOUND;
        double delay = safeDist / speed;

        return switch (env) {
            case UNDERWATER -> {
                int tinted = tintHydrological(baseRgb, biomeWaterColorRgb);
                yield new AcousticReaction(
                        EnvironmentType.UNDERWATER,
                        WATER_SPEED_OF_SOUND,
                        delay,
                        WATER_LIFETIME_MULTIPLIER,
                        1.0f,
                        1.0f,
                        tinted,
                        true,
                        false,
                        null
                );
            }
            case CAVE -> {
                GhostEcho echo = createGhostEcho(safeText, safeX, safeY, safeZ, normalX, normalY, normalZ);
                yield new AcousticReaction(
                        EnvironmentType.CAVE,
                        AIR_SPEED_OF_SOUND,
                        delay,
                        1.0,
                        1.0f,
                        1.0f,
                        baseRgb,
                        false,
                        false,
                        echo
                );
            }
            case THIN_AIR -> new AcousticReaction(
                    EnvironmentType.THIN_AIR,
                    AIR_SPEED_OF_SOUND,
                    delay,
                    1.0,
                    THIN_AIR_SCALE,
                    1.0f,
                    baseRgb,
                    false,
                    true,
                    null
            );
            case NORMAL -> new AcousticReaction(
                    EnvironmentType.NORMAL,
                    AIR_SPEED_OF_SOUND,
                    delay,
                    1.0,
                    1.0f,
                    1.0f,
                    baseRgb,
                    false,
                    false,
                    null
            );
        };
    }
}
