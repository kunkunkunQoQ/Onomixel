package dev.kunkun.onomixel.subtitle;

/**
 * Comic art styles altering font expression, motion dynamics, and chromatic rendering.
 */
public enum AestheticStyle {
    /** Classic action manga: bold brushwork, explosive burst scales, and dynamic speed angles. */
    SHONEN,
    /** 1960s retro comic pop-art: vibrant primary colors, extruded drop shadows, and punchy pop. */
    POP_ART,
    /** European fantasy parchment: gothic calligraphic italics, warm antique gold, and gentle flow. */
    MEDIEVAL,
    /** High-tech cyberpunk: electric neon cyan/magenta, chromatic aberration accents, and digital snap. */
    CYBERPUNK
}
